import { footprint, part, type PartDef } from './parts';
import { inventory } from './inventory';
import type { Brick, Model } from './types';

/**
 * LDraw export. Grid (x studs, y plates up, z studs, front = +z) maps to LDraw
 * (1 stud = 20 LDU, 1 plate = 8 LDU, -Y up) through a 180° rotation about X:
 * (x, y, z) → (x, -y, -z), which keeps the coordinate system right-handed.
 *
 * LDraw part origins sit at the center of the top face (bricks/plates/tiles)
 * with the long axis along X; slopes face -Z with the origin at the center of
 * the top stud row. Our catalog has the long axis along z at rot 0, so most
 * parts need a base quarter-turn.
 */

const LDRAW_FILE: Record<string, string> = {
  '3040': '3040b',
  '4073': '6141',
  '3665': '3665a',
  '3660': '3660a',
  '3794': '3794b',
  '3062b': '3062b',
};

type M3 = [number, number, number, number, number, number, number, number, number];
const I: M3 = [1, 0, 0, 0, 1, 0, 0, 0, 1];
const mul = (a: M3, b: M3): M3 => [
  a[0] * b[0] + a[1] * b[3] + a[2] * b[6], a[0] * b[1] + a[1] * b[4] + a[2] * b[7], a[0] * b[2] + a[1] * b[5] + a[2] * b[8],
  a[3] * b[0] + a[4] * b[3] + a[5] * b[6], a[3] * b[1] + a[4] * b[4] + a[5] * b[7], a[3] * b[2] + a[4] * b[5] + a[5] * b[8],
  a[6] * b[0] + a[7] * b[3] + a[8] * b[6], a[6] * b[1] + a[7] * b[4] + a[8] * b[7], a[6] * b[2] + a[7] * b[5] + a[8] * b[8],
];
/** Rotation about the LDraw Y axis by quarter turns. */
const rotY = (q: number): M3 => {
  const a = (q * Math.PI) / 2;
  const c = Math.round(Math.cos(a)), s = Math.round(Math.sin(a));
  return [c, 0, s, 0, 1, 0, -s, 0, c];
};

/** Base orientation that maps the LDraw part onto our rot-0 orientation (in LDraw space). */
function baseRot(def: PartDef): M3 {
  switch (def.kind) {
    case 'slope':
    case 'slopeInv':
    case 'ridge':
    case 'curve':
      // LDraw slopes face -Z; our rot 0 faces +z which is LDraw -Z after the X flip.
      return I;
    default:
      // LDraw long axis is X; ours is z. Quarter turn about Y.
      return def.l > def.w ? rotY(1) : I;
  }
}

/** Origin offset (LDraw local) of the part relative to the center of its top face. */
function originOffset(def: PartDef): [number, number, number] {
  if (def.kind === 'slope' || def.kind === 'slopeInv') {
    // origin at the center of the top stud row (back row): back row is at our low z = LDraw +Z side
    return [0, 0, (def.l / 2 - 0.5) * 20];
  }
  return [0, 0, 0];
}

function partLine(b: Brick): string {
  const def = part(b.part);
  const [sx, sz] = footprint(def, b.rot);
  const col = color(b.color).ldraw;
  // footprint center in grid → LDraw
  const cx = (b.x + sx / 2) * 20;
  const cz = -(b.z + sz / 2) * 20;
  const top = -(b.y + def.h) * 8;
  // our rot is a turn about +y (counter-clockwise from above); after the X flip it is -rot about LDraw Y
  const R = mul(rotY(-b.rot), baseRot(def));
  const [ox, oy, oz] = originOffset(def);
  const o = [R[0] * ox + R[1] * oy + R[2] * oz, R[3] * ox + R[4] * oy + R[5] * oz, R[6] * ox + R[7] * oy + R[8] * oz];
  const file = (LDRAW_FILE[b.part] ?? b.part) + '.dat';
  const n = (v: number) => String(Math.round(v * 1000) / 1000);
  return `1 ${col} ${n(cx + o[0])} ${n(top + o[1])} ${n(cz + o[2])} ${R.map(n).join(' ')} ${file}`;
}

export function toLDraw(model: Model): string {
  const lines: string[] = [];
  const safe = model.name.replace(/[^A-Za-z0-9]+/g, '_');
  const subs = [...new Set(model.bricks.map((b) => b.sub).filter(Boolean))] as string[];
  const subFile = (s: string) => `${safe}_${s.replace(/[^A-Za-z0-9]+/g, '_')}.ldr`;
  lines.push(`0 FILE ${safe}.ldr`, `0 ${model.name}`, `0 Name: ${safe}.ldr`, '0 Author: Lego It', '0 !LICENSE Generated by Lego It', '');
  for (const s of model.steps) {
    if (s.sub) continue;
    if (s.attaches) lines.push(`1 16 0 0 0 1 0 0 0 1 0 0 0 1 ${subFile(s.attaches)}`);
    for (const id of s.bricks) lines.push(partLine(model.bricks[id]));
    lines.push('0 STEP');
  }
  lines.push('0 NOFILE');
  for (const name of subs) {
    lines.push('', `0 FILE ${subFile(name)}`, `0 ${name}`, `0 Name: ${subFile(name)}`, '0 Author: Lego It');
    for (const s of model.steps) {
      if (s.sub !== name) continue;
      for (const id of s.bricks) lines.push(partLine(model.bricks[id]));
      lines.push('0 STEP');
    }
    lines.push('0 NOFILE');
  }
  return lines.join('\n') + '\n';
}

export function toCSV(model: Model): string {
  const rows = [['Part', 'Name', 'Color', 'LEGO color', 'BrickLink color id', 'LDraw color', 'Quantity']];
  for (const it of inventory(model)) {
    const c = color(it.color);
    rows.push([it.part, part(it.part).name, c.name, c.legoName, String(c.bricklink), String(c.ldraw), String(it.count)]);
  }
  return rows.map((r) => r.map((v) => (/[",]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v)).join(',')).join('\n') + '\n';
}

/** BrickLink "wanted list" XML (Want → Upload). */
export function toBrickLinkXML(model: Model): string {
  const items = inventory(model)
    .map((it) => {
      const id = it.part;
      return `  <ITEM>\n    <ITEMTYPE>P</ITEMTYPE>\n    <ITEMID>${id}</ITEMID>\n    <COLOR>${color(it.color).bricklink}</COLOR>\n    <MINQTY>${it.count}</MINQTY>\n  </ITEM>`;
    })
    .join('\n');
  return `<INVENTORY>\n${items}\n</INVENTORY>\n`;
}

/* ---------------- ordering real parts ---------------- */

export interface OrderLine {
  part: string; // app part id
  catalog: string; // catalog part number to order (Rebrickable numbering; BrickLink's for nearly all)
  color: string; // colour key to order
  wanted: string; // colour key in the model
  element?: string; // LEGO element id (Pick a Brick)
  count: number;
}
export interface OrderList {
  lines: OrderLine[];
  /** pieces whose colour was never produced in that part and are ordered in the nearest colour */
  swapped: { part: string; from: string; to: string; count: number }[];
  missing: number;
}
interface ElementTable {
  parts: Record<string, string>;
  el: Record<string, string>;
  sub: Record<string, string>;
  mould: Record<string, string>;
}
/** catalog numbers where BrickLink's own number differs from Rebrickable's */
const BL_PART: Record<string, string> = { '6141': '4073' };

let table: Promise<ElementTable> | null = null;
export const loadElements = () => (table ??= import('./elements.json').then((m) => m.default as unknown as ElementTable));

export function orderList(model: Model, t: ElementTable): OrderList {
  const merged = new Map<string, OrderLine>();
  const swapped = new Map<string, { part: string; from: string; to: string; count: number }>();
  let missing = 0;
  for (const it of inventory(model)) {
    let key = it.color;
    const sub = t.sub[`${it.part}|${key}`];
    if (!t.el[`${it.part}|${key}`] && sub) {
      const k = `${it.part}|${key}|${sub}`;
      const s = swapped.get(k) ?? { part: it.part, from: key, to: sub, count: 0 };
      s.count += it.count;
      swapped.set(k, s);
      key = sub;
    }
    const element = t.el[`${it.part}|${key}`];
    if (!element) missing += it.count;
    const catalog = t.mould[`${it.part}|${key}`] ?? t.parts[it.part] ?? it.part;
    const id = `${catalog}|${key}`;
    const line = merged.get(id) ?? { part: it.part, catalog, color: key, wanted: it.color, element, count: 0 };
    line.count += it.count;
    merged.set(id, line);
  }
  return { lines: [...merged.values()], swapped: [...swapped.values()].sort((a, b) => b.count - a.count), missing };
}

/** BrickLink Wanted List XML (also imported by Brick Owl and Rebrickable), with real part numbers and colours. */
export function orderXML(o: OrderList): string {
  const items = o.lines
    .map((l) => `  <ITEM>\n    <ITEMTYPE>P</ITEMTYPE>\n    <ITEMID>${BL_PART[l.catalog] ?? l.catalog}</ITEMID>\n    <COLOR>${color(l.color).bricklink}</COLOR>\n    <MINQTY>${l.count}</MINQTY>\n  </ITEM>`)
    .join('\n');
  return `<INVENTORY>\n${items}\n</INVENTORY>\n`;
}

/** LEGO Pick a Brick upload files (elementId,quantity), split so no file has more than `max` pieces. */
export function pickABrickCSV(o: OrderList, max = 999): string[] {
  const files: string[][] = [[]];
  let n = 0;
  for (const l of o.lines) {
    if (!l.element) continue;
    let left = l.count;
    while (left > 0) {
      if (n >= max) {
        files.push([]);
        n = 0;
      }
      const take = Math.min(left, max - n);
      files[files.length - 1].push(`${l.element},${take}`);
      n += take;
      left -= take;
    }
  }
  return files.filter((f) => f.length).map((f) => ['elementId,quantity', ...f].join('\n') + '\n');
}
